"""Maps for training: the registry (every map we can train on, as maps/splits manifest entries) and the
`MapSampler` that draws one `EnvSpec` per episode (docs/MODULE_CONTRACTS.md §5.1).

(`training.envs.map_registry` is a backward-compatible alias of this module.)

Registry:

Sources:
- generated: `maps/generated/<stage>/*.wad` + JSON sidecar from `training.envs.mapgen`;
- freedoom2: MAP01-MAP32 of the IWAD bundled with vizdoom (loaded in place, `@vizdoom/freedoom2.wad`);
- freedoom1: E1M1-E4M9 of `@vizdoom/freedoom1.wad`, loaded as a PWAD over the freedoom2 IWAD (verified to load);
- vizdoom: the scenario WADs in `@vizdoom/scenarios/` (one source group per scenario).

Bundled WADs are never copied into maps/. Schema and split rules: docs/EVALUATION_PROTOCOL.md §1. This module
never writes maps/splits/*.json (owned by the evaluation researcher); `manifest_entries()` produces dicts the
eval researcher can paste, and `check_trainable()` refuses anything that is in the val/test manifests.

    uv run --no-sync python -m training.envs.maps --sources generated,freedoom2 [--role train] [--json]
"""

from __future__ import annotations

import argparse
import functools
import hashlib
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATED_DIR = ROOT / "maps" / "generated"
SPLITS_DIR = ROOT / "maps" / "splits"
VIZDOOM_PREFIX = "@vizdoom/"
SOURCES = ("generated", "freedoom2", "freedoom1", "vizdoom")

FREEDOOM_LICENSE = "BSD-3-Clause (Freedoom; bundled with vizdoom)"
VIZDOOM_LICENSE = "MIT (ViZDoom scenarios; bundled with vizdoom)"
GENERATED_LICENSE = "project (generated by training.envs.mapgen)"


def vizdoom_dir() -> Path:
    import vizdoom

    return Path(vizdoom.__file__).resolve().parent


def resolve_wad(wad: str) -> Path:
    """Manifest `wad` field -> absolute path ("@vizdoom/<file>" or repo-relative)."""
    if wad.startswith(VIZDOOM_PREFIX):
        return vizdoom_dir() / wad.removeprefix(VIZDOOM_PREFIX)
    p = Path(wad)
    return p if p.is_absolute() else ROOT / p


@functools.lru_cache(maxsize=256)
def _sha256_cached(path: str, mtime_ns: int, size: int) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256(path: Path) -> str:
    st = path.stat()
    return _sha256_cached(str(path), st.st_mtime_ns, st.st_size)


@dataclass(frozen=True)
class MapEntry:
    id: str
    wad: str  # repo-relative or @vizdoom/<file>
    map: str
    wad_sha256: str
    source_group: str
    source: str
    license: str
    tier: int | None
    tier_basis: str
    episode_ticks: int
    tags: tuple[str, ...] = ()
    notes: str = ""
    kind: str = ""  # registry source: generated | freedoom2 | freedoom1 | vizdoom
    meta_path: str = ""  # generated maps: repo-relative sidecar path
    extra: dict = field(default_factory=dict, compare=False, hash=False)

    @property
    def path(self) -> Path:
        return resolve_wad(self.wad)

    def manifest(self, role: str) -> dict:
        """One maps/splits entry (docs/EVALUATION_PROTOCOL.md §1.4)."""
        return {
            "id": self.id, "wad": self.wad, "map": self.map, "wad_sha256": self.wad_sha256,
            "source_group": self.source_group, "source": self.source, "license": self.license,
            "tier": self.tier, "tier_basis": self.tier_basis, "episode_ticks": self.episode_ticks,
            "role": role, "tags": list(self.tags), "notes": self.notes,
        }


def _rel(p: Path) -> str:
    try:
        return p.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(p.resolve())


# ------------------------------------------------------------------------------------------ sources
def generated_entries(root: Path = GENERATED_DIR) -> list[MapEntry]:
    out = []
    for js in sorted(Path(root).glob("*/*.json")):
        meta = json.loads(js.read_text())
        if meta.get("generator") != "doomsday-udmfgen":
            continue
        wad = js.with_suffix(".wad")
        if not wad.is_file():
            raise FileNotFoundError(f"{js}: sidecar without {wad.name}")
        digest = sha256(wad)
        if digest != meta["wad_sha256"]:
            raise ValueError(f"{wad}: sha256 differs from its sidecar (regenerate or delete both)")
        tags = ["generated", meta["stage"], "exit"]
        if meta["num_doors"]:
            tags.append("door")
        if meta["num_locked_doors"]:
            tags += ["key", "locked_door"]
        if meta["num_monsters"]:
            tags.append("monster")
        out.append(MapEntry(
            id=f"gen_{meta['stage']}_{meta['family']}_{meta['seed']:06d}" + (f"_{meta['config_key']}" if meta.get("config_key") else ""),
            wad=_rel(wad), map=meta["map"], wad_sha256=digest, source_group=meta["source_group"],
            source=f"{meta['generator']} v{meta['generator_version']} stage={meta['stage']} family={meta['family']} seed={meta['seed']}",
            license=GENERATED_LICENSE, tier=meta["tier"], tier_basis="generator", episode_ticks=int(meta["episode_ticks"]),
            tags=tuple(tags), kind="generated", meta_path=_rel(js),
            notes=f"rooms={meta['room_count']} doors={meta['num_doors']} locks={meta['num_locked_doors']} "
                  f"monsters={meta['num_monsters']} exit={meta['exit']['kind']} solvable={meta['solvable']}",
            extra={"episode_ticks_range": meta.get("episode_ticks_range")},
        ))
    return out


def _list_maps(path: Path) -> list[str]:
    from doom_env.wad import list_maps, read_wad

    return list_maps(read_wad(path))


def _static_tags(path: Path, map_name: str) -> tuple[list[str], str]:
    from doom_env.mapinfo import load_mapinfo

    try:
        mi = load_mapinfo(path, map_name)
    except Exception as e:  # noqa: BLE001 - registry must not die on one odd map; reported in notes
        return [], f"mapinfo failed: {type(e).__name__}: {e}"
    tags = []
    locks = sum(1 for v in mi.door_sectors.values() if v > 0)
    if len(mi.door_sectors) - locks:
        tags.append("door")
    if locks:
        tags += ["key", "locked_door"]
    return tags, f"sectors={mi.num_sectors} doors={len(mi.door_sectors) - locks} locked={locks} format={mi.format}"


def has_player1_start(path: Path, map_name: str) -> bool:
    """Static check for a single-player start (thing type 1). Deathmatch-only maps fail make_env with
    "No player 1 start" (MEASURED: vizdoom cig MAP01, cig_with_unknown MAP01/03/04/05, multi_duel)."""
    import struct

    from doom_env.mapinfo import parse_udmf
    from doom_env.wad import map_lumps, read_wad

    lumps = map_lumps(read_wad(path), map_name)
    if "TEXTMAP" in lumps:
        things = parse_udmf(lumps["TEXTMAP"].decode("utf-8", "replace")).get("thing", [])
        return any(int(t.get("type", 0) or 0) == 1 for t in things)
    data = lumps.get("THINGS", b"")
    size, off = (20, 10) if "BEHAVIOR" in lumps else (10, 6)
    return any(struct.unpack_from("<H", data, i * size + off)[0] == 1 for i in range(len(data) // size))


def _block(n: int, size: int = 8) -> str:
    lo = (n - 1) // size * size + 1
    return f"MAP{lo:02d}-{lo + size - 1:02d}"


def freedoom2_entries() -> list[MapEntry]:
    path = vizdoom_dir() / "freedoom2.wad"
    digest = sha256(path)
    out = []
    for m in _list_maps(path):
        if not (m.startswith("MAP") and m[3:].isdigit()):
            continue
        tags, notes = _static_tags(path, m)
        out.append(MapEntry(
            id=f"fd2_{m.lower()}", wad=f"{VIZDOOM_PREFIX}freedoom2.wad", map=m, wad_sha256=digest,
            source_group=f"freedoom2:{_block(int(m[3:]))}", source="freedoom2.wad bundled with vizdoom",
            license=FREEDOOM_LICENSE, tier=None, tier_basis="none", episode_ticks=4200,
            tags=tuple(["freedoom2", "exit", *tags]), notes=notes, kind="freedoom2"))
    return out


def freedoom1_entries() -> list[MapEntry]:
    path = vizdoom_dir() / "freedoom1.wad"
    digest = sha256(path)
    out = []
    for m in _list_maps(path):
        if not (len(m) == 4 and m[0] == "E" and m[2] == "M"):
            continue
        tags, notes = _static_tags(path, m)
        out.append(MapEntry(
            id=f"fd1_{m.lower()}", wad=f"{VIZDOOM_PREFIX}freedoom1.wad", map=m, wad_sha256=digest,
            source_group=f"freedoom1:E{m[1]}", source="freedoom1.wad bundled with vizdoom, loaded over the freedoom2 IWAD",
            license=FREEDOOM_LICENSE, tier=None, tier_basis="none", episode_ticks=4200,
            tags=tuple(["freedoom1", "exit", *tags]), notes=notes, kind="freedoom1"))
    return out


def vizdoom_scenario_entries() -> list[MapEntry]:
    out = []
    for path in sorted((vizdoom_dir() / "scenarios").glob("*.wad")):
        digest = sha256(path)
        name = path.stem
        for m in _list_maps(path):
            if not has_player1_start(path, m):
                continue  # deathmatch-only map: cannot be loaded single-player
            tags, notes = _static_tags(path, m)
            out.append(MapEntry(
                id=f"vzd_{name}_{m.lower()}", wad=f"{VIZDOOM_PREFIX}scenarios/{path.name}", map=m, wad_sha256=digest,
                source_group=f"vizdoom:{name}", source=f"vizdoom scenarios/{path.name}", license=VIZDOOM_LICENSE,
                tier=None, tier_basis="none", episode_ticks=2100, tags=tuple(["vizdoom", *tags]),
                notes=notes + " (scenario .cfg rewards/ACS not applied by doom_env)", kind="vizdoom"))
    return out


_LOADERS = {"generated": generated_entries, "freedoom2": freedoom2_entries, "freedoom1": freedoom1_entries,
            "vizdoom": vizdoom_scenario_entries}


def all_entries(sources: tuple[str, ...] | list[str] = SOURCES) -> list[MapEntry]:
    out: list[MapEntry] = []
    for s in sources:
        if s not in _LOADERS:
            raise ValueError(f"unknown source {s!r}; choose from {SOURCES}")
        out += _LOADERS[s]()
    return out


# ------------------------------------------------------------------------------------- split guards
def heldout_keys(splits_dir: Path = SPLITS_DIR, splits: tuple[str, ...] = ("val", "test")) -> tuple[set[str], set[str], set[str]]:
    """(ids, source_groups, "sha256:map" keys) present in the given manifests."""
    ids, groups, pairs = set(), set(), set()
    for split in splits:
        p = Path(splits_dir) / f"{split}.json"
        if not p.is_file():
            continue
        for e in json.loads(p.read_text()).get("maps", []):
            ids.add(e["id"])
            groups.add(e["source_group"])
            pairs.add(f"{e['wad_sha256']}:{e['map']}")
    return ids, groups, pairs


def check_trainable(entries: list[MapEntry], splits_dir: Path = SPLITS_DIR) -> list[MapEntry]:
    """Raise ValueError if any entry (by id, source_group or wad sha256 + map) is in val/test. Returns entries."""
    ids, groups, pairs = heldout_keys(splits_dir)
    bad = [e.id for e in entries if e.id in ids or e.source_group in groups or f"{e.wad_sha256}:{e.map}" in pairs]
    if bad:
        raise ValueError(f"refusing held-out (val/test) maps for training: {bad[:10]}{' ...' if len(bad) > 10 else ''}")
    return entries


def manifest_entries(entries: list[MapEntry], role: str) -> list[dict]:
    if role not in ("smoke", "train", "val", "test"):
        raise ValueError(role)
    return [e.manifest(role) for e in entries]


# ------------------------------------------------------------------------------------------ sampler
TICKS_RANGE = (2100, 4200)  # docs/MODULE_CONTRACTS.md §5.1 (randomize_ticks) and the eval tick range
TRAINABLE_SPLITS = ("train", "smoke")


def _sidecar_ticks_range(wad: str) -> tuple[int, int] | None:
    """Generated maps carry `episode_ticks_range` in their JSON sidecar; None for everything else."""
    if wad.startswith(VIZDOOM_PREFIX):
        return None
    js = resolve_wad(wad).with_suffix(".json")
    if not js.is_file():
        return None
    try:
        rng = json.loads(js.read_text()).get("episode_ticks_range")
    except (OSError, ValueError):
        return None
    if isinstance(rng, list) and len(rng) == 2:
        lo, hi = int(rng[0]), int(rng[1])
        if 1 <= lo <= hi <= 4200:
            return lo, hi
    return None


def load_trainable_manifest(path: str | Path, splits_dir: Path = SPLITS_DIR) -> list[dict]:
    """Entries of a train/smoke manifest. Raises ValueError for a val/test manifest, or for any entry whose id,
    source_group or (sha256, map) is held out in maps/splits/val.json or test.json (test-set access policy)."""
    p = Path(path)
    if not p.is_absolute():
        p = ROOT / p
    man = json.loads(p.read_text())
    split = man.get("split")
    if split not in TRAINABLE_SPLITS or p.stem in ("val", "test"):
        raise ValueError(f"{p}: refusing manifest with split={split!r} for training (only {TRAINABLE_SPLITS})")
    entries = list(man.get("maps", []))
    ids, groups, pairs = heldout_keys(splits_dir)
    bad = [e["id"] for e in entries if e["id"] in ids or e["source_group"] in groups
           or f"{e['wad_sha256']}:{e['map']}" in pairs]
    if bad:
        raise ValueError(f"{p}: refusing held-out (val/test) maps for training: {bad[:10]}")
    return entries


class MapSampler:
    """Draws one `EnvSpec` per episode from train/smoke manifests (docs/MODULE_CONTRACTS.md §5.1).

    manifest_paths: train/smoke manifest files (repo-relative or absolute). val/test are refused, and so is any
        entry held out in maps/splits/val.json or test.json.
    weights: one weight per manifest (default uniform over manifests); entries within a manifest are uniform.
    rng: a numpy Generator (per env slot: `default_rng([seed_base, slot, 1])`).
    randomize_ticks: per-episode `episode_ticks` drawn uniformly from the generated map's sidecar
        `episode_ticks_range`, else from [2100, 4200]. False uses the manifest's `episode_ticks`.
    entries: optional in-memory manifest entries (dicts or MapEntry) instead of / in addition to files; they go
        through the same held-out check. Useful with `maps.all_entries(["generated"])`.
    """

    def __init__(self, manifest_paths=(), weights=None, rng: "np.random.Generator | None" = None, *,
                 randomize_ticks: bool = True, render_buffers: bool = False, mods=(), entries=None,
                 splits_dir: Path = SPLITS_DIR):
        import numpy as np

        groups: list[list[dict]] = [load_trainable_manifest(p, splits_dir) for p in manifest_paths]
        if entries:
            dicts = [e.manifest("train") if isinstance(e, MapEntry) else dict(e) for e in entries]
            ids, grp, pairs = heldout_keys(splits_dir)
            bad = [e["id"] for e in dicts if e["id"] in ids or e["source_group"] in grp
                   or f"{e['wad_sha256']}:{e['map']}" in pairs]
            if bad:
                raise ValueError(f"refusing held-out (val/test) maps for training: {bad[:10]}")
            groups.append(dicts)
        w_all = np.ones(len(groups)) if weights is None else np.asarray(weights, float)
        if w_all.shape != (len(groups),):
            raise ValueError(f"MapSampler: need one weight per manifest (+1 for `entries`), got {weights}")
        keep = [i for i, g in enumerate(groups) if g]
        if not keep:
            raise ValueError("MapSampler: no trainable maps (empty manifests)")
        groups, w = [groups[i] for i in keep], w_all[keep]
        if not (np.all(w >= 0) and w.sum() > 0):
            raise ValueError(f"MapSampler: bad weights {weights}")
        self._groups = groups
        self._p = w / w.sum()
        self.rng = rng if rng is not None else np.random.default_rng(0)
        self.randomize_ticks = bool(randomize_ticks)
        self.render_buffers = bool(render_buffers)
        self.mods = tuple(mods)
        self._ticks = {e["id"]: _sidecar_ticks_range(e["wad"]) for g in groups for e in g}

    @property
    def entries(self) -> list[dict]:
        return [e for g in self._groups for e in g]

    def with_rng(self, rng) -> "MapSampler":
        """Same maps, independent RNG (one sampler per env slot without re-reading manifests)."""
        import copy

        other = copy.copy(self)
        other.rng = rng
        return other

    def sample(self, keep: "EnvSpec | None" = None) -> "EnvSpec":
        """Next episode's spec. `keep`: stay on that map (only episode_ticks is re-drawn), which avoids a 0.3 s
        engine re-init per episode (vector env knob `episodes_per_map`)."""
        from training.envs.factory import EnvSpec

        if keep is not None:
            e = next(x for g in self._groups for x in g if x["id"] == keep.map_id)
        else:
            g = self._groups[int(self.rng.choice(len(self._groups), p=self._p))] if len(self._groups) > 1 else self._groups[0]
            e = g[int(self.rng.integers(len(g)))]
        if self.randomize_ticks:
            lo, hi = self._ticks.get(e["id"]) or TICKS_RANGE
            ticks = int(self.rng.integers(lo, hi + 1))
        else:
            ticks = int(e["episode_ticks"])
        return EnvSpec(map_id=e["id"], wad=e["wad"], map=e["map"], episode_ticks=ticks,
                       render_buffers=self.render_buffers, mods=self.mods)


def write_manifest(entries: list[MapEntry], path: str | Path, split: str = "train", description: str = "") -> Path:
    """Write a train/smoke manifest (schema 1.0) OUTSIDE maps/splits (e.g. runs/<owner>/manifests/) for MapSampler.
    maps/splits/*.json belong to the evaluation researcher and are never written here."""
    if split not in TRAINABLE_SPLITS:
        raise ValueError(f"write_manifest only writes {TRAINABLE_SPLITS} manifests")
    p = Path(path)
    if p.resolve().parent == SPLITS_DIR.resolve():
        raise ValueError("refusing to write into maps/splits/ (owned by the evaluation researcher)")
    p.parent.mkdir(parents=True, exist_ok=True)
    man = {"schema_version": "1.0", "split": split, "description": description or "training manifest from training.envs.maps",
           "created_utc": "", "owner": "environment-engineer", "seeds": [], "maps": manifest_entries(entries, split)}
    p.write_text(json.dumps(man, indent=1) + "\n")
    return p


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m training.envs.maps")
    p.add_argument("--sources", default=",".join(SOURCES))
    p.add_argument("--role", default="train")
    p.add_argument("--json", action="store_true", help="print manifest entries as JSON")
    a = p.parse_args(argv)
    entries = all_entries([s for s in a.sources.split(",") if s])
    if a.json:
        print(json.dumps(manifest_entries(entries, a.role), indent=1))
    else:
        for e in entries:
            print(f"{e.id:34s} {e.map:6s} {e.source_group:28s} tier={e.tier} ticks={e.episode_ticks} {','.join(e.tags)}")
        print(f"{len(entries)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
